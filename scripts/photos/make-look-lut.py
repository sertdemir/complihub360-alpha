#!/usr/bin/env python3
"""Bake the CompliHub photo look B ("Petrol & Papier") into a .cube 3D LUT.

The LUT is the source of truth for every marketing photo: grade-photos.py
applies it in the repo, and the same file loads in Lightroom, Photoshop or
Premiere. This script only exists so the LUT can be reproduced and tuned —
change the formula here, re-run, commit the new .cube, re-run grade-photos.py.

Look B, decided 2026-10-24 (vault: "Bildlook B — Petrol und Papier"):
  - saturation -25 %, loud non-skin colours tamed further
  - split toning: shadows toward petrol #004D40, lights toward paper #E9E4D3
    with a little logo gold #C5913B
  - never pure black: the floor lifts toward a deep petrol
  - skin tones are protected from most of the toning ("Human always")

The look depends on each pixel's own colour only, so the LUT reproduces it
exactly up to interpolation error.

Usage:
  python3 scripts/photos/make-look-lut.py [out.cube]
"""
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DEFAULT_OUT = os.path.join(ROOT, 'apps/vs1-demo/ui/assets/photos/complihub-look-b.cube')
SIZE = 33


def hexrgb(h):
    h = h.lstrip('#')
    return np.array([int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)])


PETROL, GOLD, PAPER = hexrgb('#004D40'), hexrgb('#C5913B'), hexrgb('#E9E4D3')
LW = np.array([0.2126, 0.7152, 0.0722])  # Rec. 709 luma weights


def luma(c):
    return (c * LW).sum(-1, keepdims=True)


def smooth(x, a, b):
    t = np.clip((x - a) / (b - a), 0, 1)
    return t * t * (3 - 2 * t)


def hue_sat(c):
    mx, mn = c.max(-1), c.min(-1)
    d = mx - mn
    s = np.where(mx > 0, d / np.maximum(mx, 1e-6), 0)
    r, g, b = c[..., 0], c[..., 1], c[..., 2]
    dd = np.maximum(d, 1e-6)
    h = np.where(mx == r, ((g - b) / dd) % 6, np.where(mx == g, (b - r) / dd + 2, (r - g) / dd + 4)) * 60
    return np.where(d > 0, h, 0), s


def skin_mask(c):
    """Soft mask for skin-like colours: warm hue, moderate saturation, mid luminance."""
    h, s = hue_sat(c)
    L = luma(c)[..., 0]
    m = smooth(h, 0, 8) * (1 - smooth(h, 40, 55)) * smooth(s, 0.12, 0.2) * (1 - smooth(s, 0.6, 0.75))
    return (m * smooth(L, 0.12, 0.25) * (1 - smooth(L, 0.85, 0.95)))[..., None]


def saturate(c, k):
    L = luma(c)
    return L + (c - L) * k


def tame_outliers(c, strength):
    """Pull loud, non-skin colours (a red shirt, a blue folder) toward the palette."""
    _, s = hue_sat(c)
    k = 1 - strength * smooth(s, 0.4, 0.85)[..., None] * (1 - skin_mask(c))
    return saturate(c, k)


def tone(c, tint, w):
    """Shift hue toward tint by w without changing luminance."""
    return c + (tint - (tint * LW).sum()) * w


def look_b(c):
    skin = skin_mask(c)
    c = saturate(c, 0.75 + 0.12 * skin)
    c = tame_outliers(c, 0.5)
    c = 0.5 + (c - 0.5) * 0.9
    L = luma(c)
    protect = 1 - 0.6 * skin
    c = tone(c, PETROL, (1 - L) ** 2 * 0.36 * protect)              # shadows to petrol
    c = tone(c, 0.7 * PAPER + 0.3 * GOLD, L ** 2 * 0.28 * protect)  # lights to paper and gold
    c = c + (1 - c) * np.array([0.03, 0.075, 0.07])                 # never pure black
    w = smooth(luma(c), 0.7, 1.0) * 0.1
    c = c * (1 - w) + PAPER * w
    return np.clip(c, 0, 1)


def write_cube(path, n=SIZE):
    g = np.linspace(0, 1, n)
    b, gg, r = np.meshgrid(g, g, g, indexing='ij')  # .cube: red varies fastest
    out = look_b(np.stack([r, gg, b], -1).reshape(-1, 3))
    with open(path, 'w') as f:
        f.write('TITLE "CompliHub Look B - Petrol und Papier"\n')
        f.write('# Generated by scripts/photos/make-look-lut.py - do not edit by hand.\n')
        f.write(f'LUT_3D_SIZE {n}\n')
        f.writelines(f'{x:.6f} {y:.6f} {z:.6f}\n' for x, y, z in out)


if __name__ == '__main__':
    out = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_OUT
    write_cube(out)
    print('wrote', os.path.relpath(out, ROOT))
